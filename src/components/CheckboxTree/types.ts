import React from "react";

/** Описание чекбокса компонента CheckboxTree. */
export interface ICheckboxTreeCheckboxData {
    /** Идентификатор узла. Должен быть уникальным в пределах дерева — по нему строится клавиатурная навигация. */
    id: string;
    /** Подпись чекбокса. */
    label: React.ReactNode;
    /** Признак выбора. Для узла с потомками пересчитывается компонентом. */
    checked: boolean;
    /** Признак частичного выбора: вместо галочки рисуется bulk-иконка. Для узла с потомками пересчитывается компонентом. */
    bulk?: boolean;
    /** Вложенные чекбоксы. Их состояние связано с родительским каскадно — вверх и вниз по дереву. */
    children?: ICheckboxTreeCheckboxData[];
}
